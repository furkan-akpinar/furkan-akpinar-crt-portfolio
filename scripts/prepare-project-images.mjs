import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const destination = path.join(root, 'public/images/projects/posters');
const manifestPath = path.join(root, 'scripts/project-images.manifest.json');
const metadataPath = path.join(root, 'src/content/project-artwork.ts');
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const argument = flag => process.argv[process.argv.indexOf(flag) + 1];
const presets = {
  avif: { quality: 75, effort: 6, chromaSubsampling: '4:4:4' },
  webp: { quality: 90, effort: 6, smartSubsample: true },
  jpg: { quality: 92, mozjpeg: true, chromaSubsampling: '4:4:4' },
};

function metadata(sources) {
  const entries = sources.map(source => `  { image: publicAssetUrl('/images/projects/posters/${source.name}.1536.jpg'), sourceWidth: ${source.width}, sourceHeight: ${source.height}, averageColor: ${JSON.stringify(source.averageColor)} },`);
  return `// Generated by scripts/prepare-project-images.mjs. Keep original lighting samples.\nimport { publicAssetUrl } from '../lib/public-asset.ts';\n\nexport const projectArtwork = [\n${entries.join('\n')}\n] as const;\n`;
}

if (process.argv.includes('--source-dir')) {
  const sourceDirectory = path.resolve(argument('--source-dir'));
  const colorPath = path.resolve(argument('--color-metadata'));
  assert.ok(!sourceDirectory.startsWith(destination), 'Use original artwork outside the release directory.');
  const colors = JSON.parse(await readFile(colorPath, 'utf8'));
  const manifest = { version: 1, description: 'Responsive artwork. Lossy delivery variants; source composition and sampled lighting preserved.', presets, sources: [], files: [] };
  await mkdir(destination, { recursive: true });
  sharp.concurrency(2);
  for (const name of (await readdir(sourceDirectory)).filter(file => file.endsWith('.webp')).sort()) {
    const input = await readFile(path.join(sourceDirectory, name));
    const dimensions = await sharp(input).metadata();
    const stem = path.parse(name).name;
    const color = colors.find(entry => entry.name === stem);
    assert.ok(color && color.width === dimensions.width && color.height === dimensions.height, `Missing original browser color sample: ${stem}`);
    manifest.sources.push({ name: stem, width: dimensions.width, height: dimensions.height, sha256: hash(input), averageColor: color.average });
    for (const width of [1024, 1536]) {
      const resized = await sharp(input).resize({ width, withoutEnlargement: true }).toColourspace('srgb').removeAlpha().raw().toBuffer({ resolveWithObject: true });
      for (const [format, options] of Object.entries(presets)) {
        const file = `${stem}.${width}.${format}`;
        const bytes = await sharp(resized.data, { raw: resized.info }).toFormat(format === 'jpg' ? 'jpeg' : format, options).toBuffer();
        await writeFile(path.join(destination, file), bytes);
        manifest.files.push({ file, width: resized.info.width, height: resized.info.height, bytes: bytes.length, sha256: hash(bytes) });
      }
    }
  }
  assert.equal(manifest.sources.length, 7, 'Preserve the seven approved project artworks.');
  await writeFile(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
  await writeFile(metadataPath, metadata(manifest.sources));
}

const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
assert.equal(await readFile(metadataPath, 'utf8'), metadata(manifest.sources), 'Artwork metadata must match the generation manifest.');
assert.equal(manifest.files.length, manifest.sources.length * 6);
const totals = {};
for (const entry of manifest.files) {
  const bytes = await readFile(path.join(destination, entry.file));
  assert.equal(hash(bytes), entry.sha256, `Artwork changed: ${entry.file}`);
  const dimensions = await sharp(bytes).metadata();
  assert.equal(dimensions.width, entry.width);
  assert.equal(dimensions.height, entry.height);
  const key = `${entry.width} ${path.extname(entry.file)}`;
  totals[key] = (totals[key] ?? 0) + bytes.length;
}
console.log(JSON.stringify({ verified: manifest.files.length, totals }, null, 2));
